import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(process.argv[2] || resolve(repoDir, "catalog.generated.js"));
const themes = JSON.parse(await readFile(resolve(repoDir, "themes.json"), "utf8"));

for (const theme of themes) {
  theme.themeText = await readFile(resolve(repoDir, theme.slug, "theme.txt"), "utf8");
}

const banner = "/* Generated by tools/generate-catalog.mjs; do not edit directly. */\n";
await writeFile(output, `${banner}window.GRUB_THEME_CATALOG = ${JSON.stringify(themes, null, 2)};\n`);
